import streamlit as st
import pandas as pd

from utils.helpers import get_risk_color, get_species_emoji


PRIORITY_CSS = {
    "URGENT":    ("urgent",   "#dc2626", "🔴"),
    "CAUTION":   ("caution",  "#d97706", "🟡"),
    "AWARENESS": ("awareness","#16a34a", "🟢"),
}


def render_advisory_dashboard(orchestrator):
    """
    Render the Safety Advisory dashboard.
    Displays Kannada and English advisories from Agent 2.
    """
    st.title("📢 Safety Advisory Dashboard")
    st.markdown(
        "Localized safety advisories in **Kannada** and **English**, "
        "generated by **Agent 2 (Safety Advisor)** using IBM Granite LLM 2."
    )
    st.markdown(
        '<div class="synthetic-banner">'
        '⚠️ <strong>Important:</strong> These advisories are based on historical data analysis only. '
        'They do NOT represent the confirmed current location or movement of any animal.'
        '</div>',
        unsafe_allow_html=True,
    )

    # ── Check for active result ───────────────────────────────────
    if "last_risk_result" not in st.session_state or st.session_state["last_risk_result"] is None:
        _render_no_result()
        return

    result = st.session_state["last_risk_result"]

    if not result.success:
        st.error(
            f"The last analysis failed: {result.error_message}. "
            "Please run a new analysis from the Risk Assessment page."
        )
        return

    advisory = result.safety_advisory
    risk = result.risk_assessment

    # ── Advisory header ───────────────────────────────────────────
    _render_advisory_header(advisory, risk)

    st.divider()

    # ── English + Kannada side by side ───────────────────────────
    _render_bilingual_advisories(advisory)

    st.divider()

    # ── Precautions ───────────────────────────────────────────────
    _render_precautions(advisory)

    st.divider()

    # ── Advisory metadata ─────────────────────────────────────────
    _render_advisory_meta(advisory)

    # ── Run all villages button ───────────────────────────────────
    st.divider()
    _render_batch_run_section(orchestrator)


