def _render_advisory_header(advisory, risk):
    """Render the advisory header with key metadata."""
    priority = advisory.advisory_priority
    css_class, color, icon = PRIORITY_CSS.get(priority, ("caution", "#d97706", "🟡"))

    species_str = " · ".join(
        f"{get_species_emoji(s)} {s}" for s in advisory.primary_species
    ) or "Wildlife"

    col1, col2, col3 = st.columns([3, 1, 1])
    with col1:
        st.markdown(
            f"### {icon} Advisory for **{advisory.village_name}**, {advisory.district} District"
        )
        st.caption(f"Species involved: {species_str}")
    with col2:
        st.markdown(
            f'<div style="text-align:center;padding:0.5rem">'
            f'<div style="font-size:0.75rem;color:#57606a;margin-bottom:4px">RISK LEVEL</div>'
            f'<span class="badge badge-{advisory.risk_level}">{advisory.risk_level}</span>'
            f'</div>',
            unsafe_allow_html=True,
        )
    with col3:
        st.markdown(
            f'<div style="text-align:center;padding:0.5rem">'
            f'<div style="font-size:0.75rem;color:#57606a;margin-bottom:4px">PRIORITY</div>'
            f'<span class="badge badge-{priority}">{priority}</span>'
            f'</div>',
            unsafe_allow_html=True,
        )

    # Risk score mini-bar
    score_color = get_risk_color(advisory.risk_level)
    bar_class = advisory.risk_level.lower()
    st.markdown(
        f'<div style="display:flex;align-items:center;gap:0.75rem;margin:0.5rem 0">'
        f'<span style="font-size:0.82rem;color:#57606a">Risk Score:</span>'
        f'<strong style="color:{score_color};font-size:1rem">{advisory.risk_score}/100</strong>'
        f'<div class="score-bar-track" style="flex:1;max-width:200px">'
        f'<div class="score-bar-fill {bar_class}" style="width:{advisory.risk_score}%"></div>'
        f'</div></div>',
        unsafe_allow_html=True,
    )


def _render_bilingual_advisories(advisory):
    """Render English and Kannada advisories side by side."""
    priority = advisory.advisory_priority
    css_class = PRIORITY_CSS.get(priority, ("caution",))[0]

    col_en, col_kn = st.columns(2)

    with col_en:
        st.subheader("🇬🇧 English Safety Advisory")

        llm_tag = ""
        if hasattr(advisory, "llm_available"):
            if advisory.llm_available:
                llm_tag = '<span class="llm-pill active">IBM Granite LLM 2</span>'
            else:
                llm_tag = '<span class="llm-pill fallback">Template Fallback</span>'

        st.markdown(
            f'<div class="advisory-card {css_class}">'
            f'<div class="advisory-header">'
            f'<span class="advisory-title">Safety Advisory</span>'
            f'{llm_tag}'
            f'</div>'
            f'<div class="advisory-body">{advisory.advisory_english}</div>'
            f'</div>',
            unsafe_allow_html=True,
        )

    with col_kn:
        st.subheader("🇮🇳 ಕನ್ನಡ ಸುರಕ್ಷತಾ ಸಲಹೆ")
        st.markdown(
            f'<div class="advisory-card {css_class}">'
            f'<div class="advisory-header">'
            f'<span class="advisory-title">ಸುರಕ್ಷತಾ ಸಲಹೆ</span>'
            f'</div>'
            f'<div class="advisory-body-kn">{advisory.advisory_kannada}</div>'
            f'</div>',
            unsafe_allow_html=True,
        )


def _render_precautions(advisory):
    """Render the precautions list."""
    st.subheader("✅ Recommended Precautions")

    if not advisory.precautions:
        st.info("No precautions generated.")
        return

    priority = advisory.advisory_priority
    is_urgent = priority == "URGENT"

    precaution_html = '<ul class="precaution-list">'
    for i, p in enumerate(advisory.precautions):
        # First item of URGENT advisory gets urgent style
        li_class = "urgent" if (is_urgent and i == 0) else ""
        precaution_html += f'<li class="{li_class}">{p}</li>'
    precaution_html += "</ul>"

    col_p, col_a = st.columns([2, 1])

    with col_p:
        st.markdown(precaution_html, unsafe_allow_html=True)

    with col_a:
        # Target audiences
        st.markdown("**👥 Advisory For:**")
        for audience in advisory.target_audiences:
            st.markdown(f"• {audience}")

        # Karnataka Forest Dept helpline
        st.markdown("---")
        st.markdown(
            "**📞 Karnataka Forest Department**\n\n"
            "🆓 Helpline: **1800-425-7979** (Toll-free)"
        )


def _render_advisory_meta(advisory):
    """Render advisory metadata for transparency."""
    with st.expander("ℹ️ Advisory Metadata & Transparency", expanded=False):
        col1, col2 = st.columns(2)
        with col1:
            st.markdown(f"**Village:** {advisory.village_name}")
            st.markdown(f"**District:** {advisory.district}")
            st.markdown(f"**Risk Level:** {advisory.risk_level}")
            st.markdown(f"**Risk Score:** {advisory.risk_score}/100")
        with col2:
            st.markdown(f"**Priority:** {advisory.advisory_priority}")
            st.markdown(f"**Generated:** {advisory.generated_at[:19].replace('T', ' ')}")
            model = advisory.model_used or "Template-based"
            st.markdown(f"**Agent 2 Model:** {model}")
            llm_status = "✅ IBM Granite LLM 2" if advisory.llm_available else "⚠️ Template fallback"
            st.markdown(f"**LLM Status:** {llm_status}")

        st.markdown("---")
        st.caption(
            "⚠️ This advisory is based on analysis of historical incident records only. "
            "It does not represent the confirmed current location or movement of any animal. "
            "All incident data used is synthetic demonstration data (is_synthetic = TRUE)."
        )


def _render_batch_run_section(orchestrator):
    """Allow running all villages at once for a full demo."""
    st.subheader("🚀 Generate All Village Advisories")
    st.markdown(
        "Run Agent 1 + Agent 2 for all villages in the dataset. "
        "Results will be shown in the table below."
    )

    with st.expander("⚡ Batch Analysis (Demo)", expanded=False):
        df = orchestrator.get_all_incidents()
        if df.empty:
            st.info("No data available.")
            return

        villages = sorted(df["village_name"].unique().tolist())
        st.info(f"Will run analysis for {len(villages)} village(s): {', '.join(villages)}")

        if st.button("▶️ Run All Villages", key="batch_run"):
            results_data = []
            progress_bar = st.progress(0)
            status_text = st.empty()

            for i, village in enumerate(villages):
                status_text.text(f"Analysing {village} ({i+1}/{len(villages)})...")
                result = orchestrator.run_full_analysis(village, use_db=False)

                results_data.append({
                    "Village": village,
                    "Risk Score": result.risk_assessment.risk_score if result.success else "—",
                    "Risk Level": result.risk_assessment.risk_level if result.success else "ERROR",
                    "Priority": result.safety_advisory.advisory_priority if result.success else "—",
                    "Species": ", ".join(result.risk_assessment.primary_species[:2]) if result.success else "—",
                    "Status": "✅" if result.success else "❌",
                })
                progress_bar.progress((i + 1) / len(villages))

            status_text.text("✅ All analyses complete!")

            results_df = pd.DataFrame(results_data)
            st.dataframe(results_df, width="stretch", hide_index=True)

            # Store the last result for display
            if results_data:
                st.session_state["batch_results"] = results_data
